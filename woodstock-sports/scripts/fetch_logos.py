#!/usr/bin/env python3
"""Download the brand logos from the current woodstocksports.org/brands page.

Saves each logo to images/brands/<slug>.<ext> and writes images/brands/logos.js,
which the site reads to show logos in place of brand names. Logos whose file
name doesn't match a known brand go to images/brands/unmatched/ for review.

Usage (from the woodstock-sports folder):
    python3 scripts/fetch_logos.py
    python3 scripts/fetch_logos.py --html saved-brands-page.html   # use a saved copy of the page
"""
