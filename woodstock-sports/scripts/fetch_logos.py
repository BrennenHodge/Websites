IMG_URL = re.compile(r"https://images\.squarespace-cdn\.com/[^\"'\s<>?]+")


def normalize(filename):
    stem = os.path.splitext(filename)[0].lower()
    stem = re.sub(r"(_|\s|-)?(logo|underwear)$", "", stem)
    return re.sub(r"[^a-z0-9]", "", stem)


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (logo fetch for site rebuild)"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--html", help="path to a saved copy of the brands page")
    args = ap.parse_args()

    html = open(args.html, encoding="utf-8").read() if args.html else get(PAGE).decode("utf-8", "replace")
    urls = sorted(set(IMG_URL.findall(html)))
    if not urls:
        sys.exit("No Squarespace images found on the page.")

    os.makedirs(os.path.join(OUT, "unmatched"), exist_ok=True)
    logos = {}
    for url in urls:
        filename = urllib.parse.unquote(url.rsplit("/", 1)[-1])
        ext = os.path.splitext(filename)[1].lower() or ".png"
        if ext == ".jpeg":
            ext = ".jpg"
        slug = FILE_TO_SLUG.get(normalize(filename))
        if slug and slug in logos:
            continue  # the page repeats some images
        try:
            data = get(url + "?format=500w")
        except Exception as e:  # keep going; report at the end
            print(f"  failed  {filename}: {e}")
            continue
        if slug:
            name = slug + ext
            with open(os.path.join(OUT, name), "wb") as f:
                f.write(data)
            logos[slug] = name
            print(f"  saved   {filename} -> images/brands/{name}")
        else:
            with open(os.path.join(OUT, "unmatched", filename), "wb") as f:
                f.write(data)
            print(f"  review  {filename} -> images/brands/unmatched/")

    with open(os.path.join(OUT, "logos.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/fetch_logos.py. Maps brand slug -> logo file in this folder.\n")
        f.write("window.BRAND_LOGOS = " + json.dumps(dict(sorted(logos.items())), indent=2) + ";\n")

    missing = sorted(set(FILE_TO_SLUG.values()) - set(logos))
    print(f"\n{len(logos)} logos saved.")
    if missing:
        print("No logo found for: " + ", ".join(missing))


if __name__ == "__main__":
    main()
